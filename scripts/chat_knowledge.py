#!/usr/bin/env python3
"""Build the knowledge base for the QDB website chat assistant.

Reads the site's own pages, turns them into plain text and writes
worker/src/knowledge.js, which the Cloudflare Worker sends to Claude as
reference material. Run from the repo root:

    python3 scripts/chat_knowledge.py

The deploy workflow (.github/workflows/chat-worker.yml) runs this before every
deploy, so the assistant always knows what the live site says. Hand-written
notes that are not on the site live in worker/knowledge/notes.md.

Live numbers (today's crowd %, COT readings, the basket board) are left out on
purpose: the assistant points people to the live pages instead of quoting
figures that go stale, and it must not turn them into trade calls.
"""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "worker" / "src" / "knowledge.js"
NOTES = ROOT / "worker" / "knowledge" / "notes.md"
SITE = "https://quasidb.com"

# Homepage sections that are live data and should not be quoted.
HOME_SKIP_IDS = {"live", "cot"}

# (path, url, mode). mode "full" keeps the whole page; "faq" keeps the intro
# line and the questions section only (pages full of live numbers).
PAGES = [
    ("index.html", "/", "home"),
    ("guides/index.html", "/guides/", "full"),
    ("guides/retail-sentiment/index.html", "/guides/retail-sentiment/", "full"),
    ("guides/stop-loss-clusters/index.html", "/guides/stop-loss-clusters/", "full"),
    ("guides/order-book/index.html", "/guides/order-book/", "full"),
    ("games/index.html", "/games/", "full"),
    ("games/trader-type/index.html", "/games/trader-type/", "full"),
    ("downloads/index.html", "/downloads/", "full"),
    ("cot/index.html", "/cot/", "faq"),
]


def strip_tags(fragment: str) -> str:
    s = re.sub(r"<(script|style|svg|noscript|canvas|form)\b[\s\S]*?</\1>", " ", fragment, flags=re.I)
    s = re.sub(r"<!--[\s\S]*?-->", " ", s)
    # Keep some structure so headings and list items stay readable.
    s = re.sub(r"<h[1-3][^>]*>", "\n\n## ", s, flags=re.I)
    s = re.sub(r"</h[1-3]>", "\n", s, flags=re.I)
    s = re.sub(r"<li[^>]*>", "\n- ", s, flags=re.I)
    s = re.sub(r"<(p|div|section|article|summary|details|tr|br|h[4-6])\b[^>]*>", "\n", s, flags=re.I)
    s = re.sub(r"<[^>]+>", " ", s)
    s = html.unescape(s)
    lines = [re.sub(r"[ \t ]+", " ", ln).strip() for ln in s.split("\n")]
    out, blank = [], False
    for ln in lines:
        if not ln:
            blank = True
            continue
        if blank and out:
            out.append("")
        out.append(ln)
        blank = False
    return "\n".join(out).strip()


def body_of(src: str) -> str:
    m = re.search(r"<body[^>]*>([\s\S]*)</body>", src, flags=re.I)
    s = m.group(1) if m else src
    # Drop the site header/nav and footer chrome.
    s = re.sub(r"<(nav|footer)\b[\s\S]*?</\1>", " ", s, flags=re.I)
    return s


def title_of(src: str) -> str:
    m = re.search(r"<title>([\s\S]*?)</title>", src, flags=re.I)
    return html.unescape(m.group(1)).strip() if m else ""


def home_text(src: str) -> str:
    body = body_of(src)
    for sid in HOME_SKIP_IDS:
        body = re.sub(r'<section[^>]*id="%s"[\s\S]*?</section>' % sid, " ", body, flags=re.I)
    # The scrolling ticker and the sample sheet table hold illustrative numbers.
    body = re.sub(r'<div class="ticker"[\s\S]*?</div>\s*</div>', " ", body, flags=re.I)
    body = re.sub(r"<table\b[\s\S]*?</table>", " ", body, flags=re.I)
    return strip_tags(body)


def faq_text(src: str) -> str:
    text = strip_tags(body_of(src))
    # Keep the first intro paragraph and everything from the questions heading.
    m = re.search(r"^## [^\n]*questions[^\n]*$", text, flags=re.I | re.M)
    intro = "\n".join(text.split("\n")[:6])
    if not m:
        return intro
    faq = text[m.start():]
    faq = re.split(r"\n## (Other pairs|The crowd over time)\b", faq)[0]
    return intro + "\n\n" + faq


def main() -> None:
    parts = []
    for path, url, mode in PAGES:
        p = ROOT / path
        if not p.exists():
            continue
        src = p.read_text(encoding="utf-8")
        if mode == "home":
            text = home_text(src)
        elif mode == "faq":
            text = faq_text(src)
        else:
            text = strip_tags(body_of(src))
        parts.append(f'<page url="{SITE}{url}" title="{html.escape(title_of(src))}">\n{text}\n</page>')

    notes = NOTES.read_text(encoding="utf-8").strip() if NOTES.exists() else ""
    knowledge = (
        "<site_notes>\n" + notes + "\n</site_notes>\n\n<site_pages>\n" + "\n\n".join(parts) + "\n</site_pages>"
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by scripts/chat_knowledge.py. Do not edit by hand.\n"
        "export const KNOWLEDGE = " + json.dumps(knowledge, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(knowledge):,} characters (~{len(knowledge)//4:,} tokens)")


if __name__ == "__main__":
    main()
