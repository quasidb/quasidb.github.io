#!/usr/bin/env python3
"""Hand-written blog posts: Markdown in blog/_write/ -> pages in /blog/.

Write a file such as blog/_write/my-first-post.md (copy blog/_write/TEMPLATE.md),
commit it, and .github/workflows/blog-write.yml runs this script, which:
  - builds blog/my-first-post/index.html in the site's style,
  - adds a card to blog/index.html and an item to blog/feed.xml (first time only),
  - adds the page to sitemap.xml.
Editing the .md later rebuilds the page. Files whose name starts with "_" or is
TEMPLATE.md / README.md are ignored. The folder starts with "_" so GitHub Pages
does not publish the raw Markdown.

    python3 scripts/blog_manual.py            # build every post in blog/_write/
    python3 scripts/blog_manual.py --check    # build into a temp copy, write nothing
"""
import argparse
import html
import os
import re
import shutil
import sys
from datetime import datetime, timezone

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from blog_auto import (SITE, HOW_TO_TRADE, attr, plain, add_to_index, add_to_feed,  # noqa: E402
                       add_to_sitemap, load_snaps, crowd_section)

SKIP = {"TEMPLATE.md", "README.md"}
MARK = "<!-- Generated by scripts/blog_manual.py from blog/_write/"


def parse(path):
    """Front matter between --- lines, then a Markdown body."""
    text = open(path, encoding="utf-8").read().replace("\r\n", "\n")
    m = re.match(r"---\n(.*?)\n---\n(.*)", text, re.S)
    if not m:
        raise SystemExit(f"{path}: needs a header between two --- lines (see TEMPLATE.md)")
    meta = {}
    for line in m.group(1).split("\n"):
        if ":" in line and not line.strip().startswith("#"):
            k, v = line.split(":", 1)
            meta[k.strip().lower()] = v.strip().strip('"').strip("'")
    for k in ("title", "description"):
        if not meta.get(k):
            raise SystemExit(f"{path}: the header needs a '{k}:' line")
    return meta, m.group(2).strip()


def to_html(md):
    import markdown
    return markdown.markdown(md, extensions=["extra", "sane_lists"])


def render(meta, body_html, slug, when, snaps):
    kind = "site" if meta.get("type", "").lower().startswith("site") else "market"
    tags = [t.strip() for t in meta.get("tags", "").split(",") if t.strip()]
    title, em = meta["title"], meta.get("highlight", "")
    full = title + (": " + em if em else "")
    h1 = html.escape(title) + (f": <em>{html.escape(em)}</em>" if em else "")
    url = f"{SITE}/blog/{slug}/"
    kick = " · ".join(["Site update" if kind == "site" else "Market note"] + [html.escape(t) for t in tags[:4]])
    extra = ""
    if kind == "market":
        pairs = [p.replace("/", "").upper() for p in meta.get("crowd", "").split(",") if p.strip()]
        extra = crowd_section(pairs, snaps) + HOW_TO_TRADE
    body_html = re.sub(r"<h2>", '</section>\n  <section class="sec">\n    <h2>', body_html)
    body_html = re.sub(r'^</section>\n  <section class="sec">\n', "", body_html)  # body opened with a heading
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>{attr(full)} | QDB Blog</title>
<meta name="description" content="{attr(meta['description'])}">
<link rel="canonical" href="{url}">
<meta property="og:type" content="article">
<meta property="og:site_name" content="QDB Trading Desk">
<meta property="og:url" content="{url}">
<meta property="og:title" content="{attr(full)}">
<meta property="og:description" content="{attr(meta['description'])}">
<meta property="og:image" content="{SITE}/og-image.png">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="article:published_time" content="{when.strftime('%Y-%m-%dT%H:%M:%SZ')}">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="{attr(full)}">
<meta name="twitter:description" content="{attr(meta['description'])}">
<meta name="twitter:image" content="{SITE}/og-image.png">
<meta name="theme-color" content="#0b0f17">
<link rel="icon" href="../../logo.png">
<link rel="alternate" type="application/rss+xml" title="QDB Blog" href="../feed.xml">
<script data-goatcounter="https://quasidb.goatcounter.com/count" async src="https://gc.zgo.at/count.js"></script>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Space+Grotesk:wght@400;500;600;700&family=JetBrains+Mono:wght@400;600;700&display=swap" rel="stylesheet">
<link rel="stylesheet" href="../../guides/guides.css">
<link rel="stylesheet" href="../blog.css">
</head>
<body>
{MARK}{slug}.md. Edit that file, not this one. -->
<nav class="top"><div class="wrap">
  <a class="brand" href="../../?ref=blog"><img src="../../logo.png" alt="">QDB Trading Desk</a>
  <div class="navl"><a href="../" aria-current="page">Blog</a><a href="../../guides/?ref=blog">Guides</a><a href="../../sentiment/?ref=blog">Sentiment</a><a href="../../?ref=blog#pricing">Pricing</a></div>
</div></nav>
<main class="wrap">
<article class="post">
  <header class="hero">
    <p class="kick">{kick}</p>
    <h1>{h1}</h1>
    <p class="meta">{when.strftime('%A %-d %B %Y')} · by Dave</p>
  </header>
  <section class="sec">
{body_html}
  </section>{extra}

  <p class="foot">Educational only, not financial advice. Trading on margin carries a high level of risk and the majority of retail CFD accounts lose money. <a href="../">All posts</a> · <a href="../feed.xml">RSS</a> · <a href="../../">QDB Trading Desk</a></p>
</article>
</main>
</body>
</html>
"""


def build(blog_dir, sitemap, snaps):
    src = os.path.join(blog_dir, "_write")
    if not os.path.isdir(src):
        return []
    index = open(os.path.join(blog_dir, "index.html"), encoding="utf-8").read()
    done = []
    for name in sorted(os.listdir(src)):
        if not name.endswith(".md") or name in SKIP or name.startswith("_"):
            continue
        slug = name[:-3].lower()
        if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", slug):
            raise SystemExit(f"{name}: use lowercase words and hyphens only, e.g. my-first-post.md")
        meta, md = parse(os.path.join(src, name))
        out_dir = os.path.join(blog_dir, slug)
        page = os.path.join(out_dir, "index.html")
        if os.path.exists(page) and MARK not in open(page, encoding="utf-8").read():
            raise SystemExit(f"{name}: blog/{slug}/ already exists and wasn't made from _write. Pick another file name.")
        try:
            when = datetime.strptime(meta.get("date", ""), "%Y-%m-%d").replace(hour=9, tzinfo=timezone.utc)
        except ValueError:
            when = datetime.now(timezone.utc).replace(microsecond=0)
        kind = "site" if meta.get("type", "").lower().startswith("site") else "market"
        os.makedirs(out_dir, exist_ok=True)
        new = render(meta, to_html(md), slug, when, snaps)
        old = open(page, encoding="utf-8").read() if os.path.exists(page) else ""
        if new != old:
            open(page, "w", encoding="utf-8").write(new)
        d = {"slug": slug, "title": meta["title"], "title_em": meta.get("highlight", ""),
             "description": meta["description"], "tags": [t.strip() for t in meta.get("tags", "").split(",") if t.strip()]}
        if f'href="{slug}/"' not in index:
            add_to_index(os.path.join(blog_dir, "index.html"), d, when, kind)
            add_to_feed(os.path.join(blog_dir, "feed.xml"), d, when, kind)
            if sitemap and os.path.exists(sitemap):
                add_to_sitemap(sitemap, slug, when.strftime("%Y-%m-%d"))
            index = open(os.path.join(blog_dir, "index.html"), encoding="utf-8").read()
        done.append(slug)
    return done


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--blog", default="blog")
    ap.add_argument("--sitemap", default="sitemap.xml")
    ap.add_argument("--history", default="data/crowd-history.json")
    ap.add_argument("--check", action="store_true", help="build into a temporary copy and write nothing")
    a = ap.parse_args()
    blog, sitemap = a.blog, a.sitemap
    if a.check:
        tmp = "/tmp/blog-write-check"
        shutil.rmtree(tmp, ignore_errors=True)
        shutil.copytree(blog, tmp)
        blog, sitemap = tmp, None
    built = build(blog, sitemap, load_snaps(a.history))
    print("Built:", ", ".join(built) or "(no posts in blog/_write yet)")


if __name__ == "__main__":
    main()
